RUBRIC_WEIGHTS = {
    "technicalAccuracy": 0.4,
    "completeness": 0.25,
    "practicalExamples": 0.2,
    "understanding": 0.15,
}


def _max_marks(difficulty: str) -> int:
    return {"Beginner": 8, "Intermediate": 10, "Advanced": 12}.get(difficulty, 10)


def _rubric(concepts: List[str], qtype: str) -> dict:
    focus = ', '.join(concepts)
    return {
        "technicalAccuracy": f"40%: Explain the relevant concepts accurately: {focus}.",
        "completeness": f"25%: Address the whole {qtype.replace('_', ' ')} question, including {focus}.",
        "practicalExamples": "20%: Give a specific example, your actions and a measurable or observable outcome.",
        "understanding": f"15%: Explain the reasoning, limitations and trade-offs behind {concepts[0] if concepts else 'your approach'}.",
    }


def _q(
    text: str,
    qtype: str,
    difficulty: str,
    source_claim: str,
    concepts: List[str],
    skill: Optional[str] = None,
    follow_ups: Optional[List[str]] = None,
) -> dict:
    return {
        "id": "Q" + hashlib.sha256(f"{difficulty}|{qtype}|{text}".encode()).hexdigest()[:12],
        "text": text,
        "type": qtype,
        "difficulty": difficulty,
        "skill": skill,
        "sourceClaim": source_claim,
        "expectedConcepts": [c.lower() for c in concepts],
        "rubric": _rubric(concepts, qtype),
        "maxMarks": _max_marks(difficulty),
        "followUpTemplates": follow_ups or [],
        "isFollowUp": False,
    }


def _detect_family(skills: List[str], text: str) -> str:
    lowered = " ".join(skills).lower() + " " + text.lower()
    data_terms = ["machine learning", "nlp", "data", "model", "pandas", "tensorflow", "pytorch", "scikit"]
    if any(term in lowered for term in data_terms):
        return "data"
    return "software"


def _project_snippet(project: dict, limit: int = 140) -> str:
    text = (project.get("text") or "").strip().replace("\n", " ")
    return text[:limit]


def generate_questions(
    profile: dict,
    findings: Optional[List[dict]] = None,
    difficulty: str = "Intermediate",
    count: int = 8,
    seed: str = "",
    interview_type: Optional[str] = None,
    confirmed_domains: Optional[List[str]] = None,
) -> dict:
    """Generate a deterministic, personalized question set."""
    if difficulty not in DIFFICULTIES:
        difficulty = "Intermediate"
    count = max(3, min(15, int(count)))

    skills = [s.get("skill") for s in (profile.get("skills") or []) if s.get("skill")]
    projects = profile.get("projects") or []
    experience = profile.get("experience") or []
    education = profile.get("education") or []
    findings = findings or []
    full_text = " ".join(
        [profile.get("summary") or ""]
        + [p.get("text") or "" for p in projects]
        + [e.get("text") or "" for e in experience]
    )

    pool: List[dict] = []

    # 1) Fundamentals for recognized skills ------------------------------
    fundamentals_covered = set()
    for skill in skills:
        bank = FUNDAMENTALS.get(skill)
        if not bank:
            continue
        # Only use entries at the requested difficulty; otherwise the
        # skill-application question for that difficulty is used instead.
        chosen = [b for b in bank if b["difficulty"] == difficulty]
        if chosen:
            fundamentals_covered.add(skill)
        for entry in chosen[:2]:
            pool.append(
                _q(
                    entry["question"],
                    "fundamentals",
                    entry["difficulty"],
                    source_claim=f"Resume lists {skill}",
                    concepts=entry["concepts"],
                    skill=skill,
                    follow_ups=[f"Can you give a concrete example involving {skill}?"],
                )
            )

    # 2) Skill-application questions for other claimed skills ------------
    for skill in skills:
        if skill in fundamentals_covered:
            continue
        template = SKILL_TEMPLATES[difficulty]
        pool.append(
            _q(
                template["question"].format(skill=skill),
                "skill_application",
                difficulty,
                source_claim=f"Resume lists {skill}",
                concepts=template["concepts"],
                skill=skill,
                follow_ups=[f"Which part of that work did you personally build with {skill}?"],
            )
        )

    # 3) Project questions ----------------------------------------------
    project_questions = [
        (
            "project",
            "What problem did this project solve, and who was it for?",
            ["problem", "users", "outcome", "scope"],
        ),
        (
            "project",
            "What was your personal contribution to this project, and which parts did you build yourself?",
            ["personal contribution", "specifics", "decisions", "ownership"],
        ),
        (
            "project",
            "How did you test or evaluate this project, and what did the results show?",
            ["testing", "evaluation", "results", "validation"],
        ),
    ]
    if difficulty == "Advanced":
        project_questions.append(
            (
                "architecture",
                "If this project had to handle ten times the load, what would you change architecturally?",
                ["architecture", "scaling", "bottleneck", "trade-offs", "caching"],
            )
        )
    for i, project in enumerate(projects[:3]):
        snippet = _project_snippet(project)
        if not snippet:
            continue
        qtype, question, concepts = project_questions[-1] if difficulty == "Advanced" else project_questions[i % len(project_questions)]
        pool.append(
            _q(
                f"Your resume mentions: “{snippet}”. {question}",
                qtype,
                difficulty,
                source_claim=snippet,
                concepts=concepts,
                follow_ups=["Which specific part was the hardest, and why?"],
            )
        )

    # 4) Experience questions -------------------------------------------
    for exp in experience[:2]:
        text = (exp.get("text") or "")[:120]
        if not text:
            continue
        pool.append(
            _q(
                f"In your role described as “{text}”, what was your biggest technical challenge and how did you solve it?",
                "experience",
                difficulty,
                source_claim=text,
                concepts=["challenge", "approach", "outcome", "learning"],
                follow_ups=["What would you do differently next time?"],
            )
        )

    # 5) Findings-driven verification questions -------------------------
    handled_types = set()
    for f in findings:
        ftype = f.get("type")
        claim = str(f.get("claim") or "")
        finding_key = (ftype, claim)
        if finding_key in handled_types:
            continue
        handled_types.add(finding_key)
        if ftype in ("skill_without_context",):
            pool.append(
                _q(
                    f"Your resume lists “{claim or 'a skill without context'}”. Describe where and how you used this skill, and what you personally built.",
                    "verification",
                    difficulty,
                    source_claim=str(f.get("claim") or "Skill without context"),
                    concepts=["context", "application", "example", "outcome"],
                    skill=next((s for s in skills if s.lower() in claim.lower()), None),
                    follow_ups=["Can you point to a specific project or task?"],
                )
            )
        elif ftype in ("similar_projects",):
            pool.append(
                _q(
                    "Two project descriptions on your resume read very similarly. How did your contribution differ between them?",
                    "verification",
                    difficulty,
                    source_claim=str(f.get("claim") or "Similar project descriptions"),
                    concepts=["difference", "personal contribution", "specifics"],
                    follow_ups=["Which one are you prouder of, and why?"],
                )
            )
        elif ftype in ("years_mismatch",):
            pool.append(
                _q(
                    "The total years of experience stated on your resume is longer than the listed roles span. What does that total include?",
                    "verification",
                    difficulty,
                    source_claim=str(f.get("claim") or "Years of experience"),
                    concepts=["timeline", "additional work", "clarity", "accuracy"],
                    follow_ups=["Which of those experiences is most relevant to this kind of role?"],
                )
            )
        elif ftype in ("date_overlap",):
            pool.append(
                _q(
                    "Two roles on your resume overlap in time. How did you balance them, and what were you responsible for in each?",
                    "verification",
                    difficulty,
                    source_claim=str(f.get("claim") or "Overlapping roles"),
                    concepts=["balance", "responsibilities", "time management", "clarity"],
                    follow_ups=["What did a typical week look like?"],
                )
            )
        elif ftype == "date_order":
            pool.append(_q(
                f"Your resume includes “{claim}”. Please clarify the start and end dates and the work you performed during that period.",
                "verification", difficulty, source_claim=claim,
                concepts=["timeline", "responsibilities", "clarity"],
            ))
        elif ftype in ("missing_projects",):
            pool.append(
                _q(
                    "Your resume does not describe a projects section. Walk me through a project you built end to end, including what you owned.",
                    "project",
                    difficulty,
                    source_claim="No projects section detected",
                    concepts=["problem", "ownership", "implementation", "outcome"],
                    follow_ups=["What did you learn from it?"],
                )
            )

    # 6) Scenario question ----------------------------------------------
    # The scenario is generic by design, so it is prefixed with the candidate's
    # own technologies instead of quoting a claim that does not exist.
    family = _detect_family(skills, full_text)
    scenario = SCENARIOS[family][difficulty]
    named_skills = [s for s in skills[:3]]
    context = (
        f"Your resume lists {', '.join(named_skills)}. " if named_skills else ""
    )
    pool.append(
        _q(
            context + scenario["question"],
            "scenario",
            difficulty,
            source_claim="",
            concepts=scenario["concepts"],
            skill=named_skills[0] if named_skills else None,
            follow_ups=["What signals would tell you the fix actually worked?"],
        )
    )

    # 7) Education question (if present) ---------------------------------
    for field, qtype, prompt in [
        ("certifications", "certification", "What did you learn, and how have you applied that knowledge?"),
        ("achievements", "achievement", "What was your contribution, and what evidence supports the result?"),
        ("responsibilities", "experience", "Explain your personal responsibility, the decisions you made and the outcome."),
    ]:
        for item in (profile.get(field) or [])[:2]:
            claim = str(item.get("text") or "").strip()[:180]
            if claim:
                pool.append(_q(f"Your resume mentions “{claim}”. {prompt}", qtype, difficulty,
                               claim, ["personal contribution", "application", "outcome", "example"]))
    if education:
        edu_text = (education[0].get("text") or "")[:120]
        pool.append(
            _q(
                f"Your resume lists “{edu_text}”. Which courses or projects from that background are most relevant to the work you want to do?",
                "background",
                difficulty,
                source_claim=edu_text,
                concepts=["relevance", "coursework", "application", "motivation"],
                follow_ups=["How did you apply that knowledge outside class?"],
            )
        )

    # Deterministic ordering (seeded) + difficulty preference -------------
    if not pool:
        pool.append(
            _q(
                SCENARIOS[family][difficulty]["question"],
                "scenario",
                difficulty,
                source_claim="No resume content available",
                concepts=SCENARIOS[family][difficulty]["concepts"],
            )
        )

    # Deterministic ordering: stable hash of (seed + question text). No random ids.
    def stable_key(q: dict) -> str:
        return hashlib.sha256(((seed or "verihire") + "|" + q["text"]).encode()).hexdigest()

    pool.sort(key=stable_key)

    selected: List[dict] = []
    seen = set()
    selected_ids = set()

    def take(predicate, limit: int) -> None:
        """Add up to `limit` matches, skipping duplicates, preserving order."""
        added = 0
        for q in pool:
            if len(selected) >= count or added >= limit:
                break
            if q["id"] in selected_ids or q["text"] in seen:
                continue
            if predicate(q):
                selected.append(q)
                selected_ids.add(q["id"])
                seen.add(q["text"])
                added += 1

    # Guarantee a balanced mix and a natural interview arc: a resume-grounded
    # warm-up first, then project work, verification of claims and scenarios.
    # Designing the order is the point: the candidate sees each type only after
    # the previous one, one question at a time.
    take(lambda q: q["type"] == "fundamentals", 1)
    take(lambda q: q["type"] == "skill_application", 1)
    take(lambda q: q["type"] in ("project", "architecture"), 1)
    take(lambda q: q["type"] == "verification", 1)
    take(lambda q: q["type"] == "experience", 1)
    take(lambda q: q["type"] == "scenario", 1)
    take(lambda q: q["type"] == "fundamentals", 2)
    take(lambda q: q["type"] in ("project", "architecture"), 2)
    take(lambda q: q["type"] == "skill_application", 2)
    take(lambda q: q["type"] == "verification", 2)
    take(lambda q: q["type"] == "experience", 2)
    take(lambda q: q["type"] == "background", 1)
    # Fill any remaining slots in deterministic order.
    for q in pool:
        if len(selected) >= count:
            break
        if q["id"] in selected_ids or q["text"] in seen:
            continue
        selected.append(q)
        selected_ids.add(q["id"])
        seen.add(q["text"])

    if confirmed_domains:
        from .domains import CATALOG, domain_questions
        grounded = [q for q in pool if q['type'] in ('project', 'architecture', 'experience', 'verification', 'background', 'certification', 'achievement')]
        allowed = {skill for domain in confirmed_domains for skill in CATALOG['domains'].get(domain, {}).get('skills', [])}
        relevant_skills = [q for q in pool if q['type'] in ('fundamentals', 'skill_application') and q.get('skill') in allowed]
        pool = list({q['id']: q for q in domain_questions(confirmed_domains, difficulty) + relevant_skills + grounded}.values())
        selected = pool[:count]
    if interview_type:
        # Live interview types reuse the same bank and actual resume sources.
        intro = _q("Please introduce yourself and explain how your background relates to the role you want.",
                   "introduction", difficulty, profile.get("summary") or "",
                   ["background", "relevance", "goals"])
        people = [
            _q("What kind of role are you looking for, and why does it interest you?", "hr", difficulty,
               profile.get("summary") or "", ["motivation", "relevance", "goals"]),
            _q("Tell me about a time you faced a difficult problem. What did you do, and what did you learn?",
               "behavioral", difficulty, "", ["challenge", "approach", "outcome", "learning"]),
            _q("Describe a disagreement while working with others. How did you communicate and reach a decision?",
               "behavioral", difficulty, "", ["context", "communication", "collaboration", "outcome"]),
            _q("How do you prioritize work when several tasks have the same deadline? Give an example.",
               "hr", difficulty, "", ["prioritization", "constraints", "communication", "example"]),
        ]
        choices = {
            "HR": people + [q for q in pool if q["type"] in ("certification", "achievement")],
            "Behavioral": [q for q in people if q["type"] == "behavioral"] + people[:1],
            "Technical": [q for q in pool if q["type"] in ("fundamentals", "skill_application", "scenario", "verification")],
            "Project-based": [q for q in pool if q["type"] in ("project", "architecture", "experience", "verification")],
            "Mixed": selected[:3] + [q for q in pool if q["type"] in ("certification", "achievement")][:1] + people[:2] + selected[3:],
        }.get(interview_type, selected)
        selected = [intro]
        for q in choices:
            if q["text"] not in {x["text"] for x in selected} and len(selected) < count:
                selected.append(q)
    selected = selected[:count]

    return {
        "difficulty": difficulty,
        "count": len(selected),
        "questions": selected,
        "generatedBy": "curated question bank + deterministic resume personalization (no generative model)",
        "note": (
            "Questions are derived from your resume's claims and skills. They are not "
            "generated by a large language model."
        ),
    }
