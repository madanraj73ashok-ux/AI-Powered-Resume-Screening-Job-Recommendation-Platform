"""Tests for personalized question generation and rubric-based scoring."""

from fastapi.testclient import TestClient

from app.main import app
from app.questions import generate_questions
from app.scoring import evaluate_answer

client = TestClient(app)

PROFILE = {
    "name": "Walte Okune",
    "contact": {"email": "walteokune@email.com"},
    "summary": "Robotics Engineer with experience in autonomous systems.",
    "skills": [
        {"skill": "Python", "category": "programming_languages", "evidence": None},
        {"skill": "Machine Learning", "category": "ml_ai", "evidence": None},
        {"skill": "Robotics Engineering", "category": "resume_skills_section", "evidence": None},
        {"skill": "Control Systems", "category": "resume_skills_section", "evidence": None},
    ],
    "education": [{"text": "BSc Robotics Engineering, MIT, 2017 - 2021"}],
    "experience": [
        {"text": "Robotics Engineer, Kuphal Inc, March 2023 - Present"},
        {"text": "Robotics Engineer, Lemke - Rice, March 2021 - March 2023"},
    ],
    "projects": [
        {
            "text": "Built an autonomous navigation module for warehouse robots using Python and ROS."
        }
    ],
}

FINDINGS = [
    {"type": "missing_projects", "claim": "Projects section", "status": "Needs Review"},
    {"type": "years_mismatch", "claim": "5 years of experience", "status": "Needs Review"},
]


def test_generation_returns_requested_count_and_personalized_content():
    result = generate_questions(PROFILE, FINDINGS, difficulty="Intermediate", count=8, seed="r1")
    questions = result["questions"]
    assert len(questions) == 8
    assert result["difficulty"] == "Intermediate"
    assert "not generated by a large language model" in result["note"].lower()

    skills_mentioned = " ".join(q["text"] for q in questions)
    assert "Python" in skills_mentioned or "Machine Learning" in skills_mentioned
    # project-derived and finding-derived questions exist
    assert any("warehouse robots" in q["text"] for q in questions)
    assert any("years of experience" in (q["sourceClaim"] or "").lower() for q in questions)

    for q in questions:
        assert q["id"].startswith("Q")
        assert q["maxMarks"] > 0
        assert q["expectedConcepts"]
        assert set(q["rubric"].keys()) == {
            "technicalAccuracy",
            "completeness",
            "practicalExamples",
            "understanding",
        }


def test_generation_is_deterministic_for_same_seed():
    a = generate_questions(PROFILE, FINDINGS, "Intermediate", 6, seed="same")
    b = generate_questions(PROFILE, FINDINGS, "Intermediate", 6, seed="same")
    assert [q["text"] for q in a["questions"]] == [q["text"] for q in b["questions"]]


def test_beginner_generation_is_gentler_than_advanced():
    beginner = generate_questions(PROFILE, [], "Beginner", 5, seed="x")
    advanced = generate_questions(PROFILE, [], "Advanced", 5, seed="x")
    assert all(q["maxMarks"] <= 8 for q in beginner["questions"])
    assert any(q["maxMarks"] >= 10 for q in advanced["questions"])


GOOD_ANSWER = (
    "In my warehouse robotics project I used Python to build the navigation module. "
    "I chose a list of waypoints stored in a mutable structure and a tuple for fixed "
    "configuration because tuples are immutable and slightly cheaper in memory. "
    "For example, I benchmarked both approaches and reduced memory usage by 30%. "
    "The trade-off was that tuples cannot be updated in place, so I replaced them "
    "when routes changed at runtime."
)

QUESTION = {
    "text": "What is the difference between a Python list and a tuple, and when would you choose one over the other?",
    "expectedConcepts": ["mutability", "list", "tuple", "performance", "use case"],
    "maxMarks": 10,
    "rubric": {},
}


def test_strong_answer_scores_higher_than_weak_answer():
    strong = evaluate_answer(QUESTION, GOOD_ANSWER, "Intermediate")
    weak = evaluate_answer(QUESTION, "Lists are like arrays and tuples are similar.", "Intermediate")
    assert strong["marksAwarded"] > weak["marksAwarded"]
    assert strong["percentage"] >= 60
    assert weak["percentage"] < strong["percentage"]
    assert strong["missingConcepts"] == []
    assert weak["missingConcepts"]


def test_empty_answer_scores_zero_and_is_not_a_character_judgement():
    result = evaluate_answer(QUESTION, "", "Intermediate")
    assert result["marksAwarded"] == 0
    assert "not a judgement about the candidate" in result["explanation"]
    assert result["missingConcepts"] == QUESTION["expectedConcepts"]


def test_scoring_includes_rubric_breakdown_and_follow_up():
    result = evaluate_answer(QUESTION, "A list is mutable while a tuple is immutable.", "Intermediate")
    assert set(result["breakdown"].keys()) == {
        "technicalAccuracy",
        "completeness",
        "practicalExamples",
        "understanding",
    }
    assert 0 <= result["marksAwarded"] <= QUESTION["maxMarks"]
    # missing concepts produce a targeted follow-up
    assert result["missingConcepts"]
    assert result["suggestedFollowUp"]
    assert result["missingConcepts"][0] in result["suggestedFollowUp"]


def test_http_generate_questions():
    res = client.post(
        "/generate-questions",
        json={"profile": PROFILE, "findings": FINDINGS, "difficulty": "Beginner", "count": 5},
    )
    assert res.status_code == 200
    body = res.json()
    assert len(body["questions"]) == 5
    assert all(q["difficulty"] == "Beginner" for q in body["questions"])


def test_http_generate_rejects_bad_difficulty_and_count():
    bad_difficulty = client.post(
        "/generate-questions",
        json={"profile": PROFILE, "difficulty": "Impossible", "count": 5},
    )
    assert bad_difficulty.status_code == 422
    bad_count = client.post(
        "/generate-questions",
        json={"profile": PROFILE, "difficulty": "Beginner", "count": 99},
    )
    assert bad_count.status_code == 422


def test_http_evaluate_answer():
    res = client.post(
        "/evaluate-answer",
        json={"question": QUESTION, "answer": GOOD_ANSWER, "difficulty": "Intermediate"},
    )
    assert res.status_code == 200
    body = res.json()
    assert body["marksAwarded"] > 0
    assert "breakdown" in body


def test_http_evaluate_rejects_empty_answer():
    res = client.post(
        "/evaluate-answer",
        json={"question": QUESTION, "answer": "   ", "difficulty": "Intermediate"},
    )
    assert res.status_code == 422


def test_interview_options_endpoint():
    res = client.get("/interview/options")
    assert res.status_code == 200
    assert res.json()["difficulties"] == ["Beginner", "Intermediate", "Advanced"]


def test_opening_question_is_resume_grounded_and_claims_are_real():
    result = generate_questions(PROFILE, FINDINGS, "Intermediate", 8, seed="flow")
    first = result["questions"][0]
    # A real interview opens on the candidate's own material, not a generic scenario.
    assert first["type"] in ("fundamentals", "skill_application", "project", "architecture")
    assert first["sourceClaim"]

    for q in result["questions"]:
        assert "Scenario based on the technologies" not in (q["sourceClaim"] or "")
        assert "Scenario based on the technologies" not in q["text"]

    scenarios = [q for q in result["questions"] if q["type"] == "scenario"]
    if scenarios:
        # Generic scenarios name the candidate's technologies instead of
        # quoting a claim that is not on the resume.
        assert scenarios[0]["sourceClaim"] == ""
        assert any(skill in scenarios[0]["text"] for skill in ("Python", "Machine Learning"))


def test_rubric_recognises_ordinary_engineering_language():
    """A concrete, well-explained answer should not be penalised for wording."""
    question = {
        "text": (
            "Describe how you applied Software Development in a real project. "
            "What did you build, and what alternatives or trade-offs did you consider?"
        ),
        "expectedConcepts": ["application", "alternatives", "trade-offs", "outcome", "example"],
        "maxMarks": 10,
    }
    detailed = (
        "In my last role I built a telemetry service for a fleet of robots. It ingested "
        "per-second status messages from 40 robots, stored them in MongoDB and exposed an "
        "Express API the operations team used. I chose MongoDB because each robot sends a "
        "different set of sensor fields, so a fixed schema would have meant constant "
        "migrations. The trade-off was weaker aggregation, so I kept a daily rollup "
        "collection. I owned the ingestion worker and wrote the load test that proved it "
        "could handle 600 messages per second before we shipped."
    )
    vague = "I used software development in projects and it went fine."

    strong = evaluate_answer(question, detailed)
    poor = evaluate_answer(question, vague)

    assert strong["matchedConcepts"] == ["application", "alternatives", "trade-offs", "outcome", "example"]
    assert strong["marksAwarded"] >= 8
    assert poor["marksAwarded"] <= 2
    assert strong["marksAwarded"] > poor["marksAwarded"]
